/**
 * 종점 이름을 짧게 다듬는다.
 *
 * "율리공영차고지종점"처럼 긴 이름이 그대로 들어오면 도착 카드의 좌측이 좁아져
 * "5개 정류장 전"까지 줄바꿈된다. 방면을 알리는 데 "종점"·"기점" 같은 접미사는
 * 필요하지 않다.
 *
 * 다 깎아내서 빈 문자열이 되면 원본을 돌려준다 — 이름 전체가 "차고지"인
 * 정류장도 있을 수 있고, 그때 빈칸을 보여주는 것이 가장 나쁘다.
 */
export function shortenPlace(name: string): string {
  const trimmed = name
    .replace(/\((?:기점|종점|회차지)\)/g, '')
    .replace(/(공영)?차고지(종점)?$/, '')
    .replace(/(종점|기점)$/, '')
    .trim()

  return trimmed || name
}
